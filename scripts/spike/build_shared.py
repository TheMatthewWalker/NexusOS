#!/usr/bin/env python3
"""Generate the SpaceUI spike's shared inputs from the design pack.

docs/design/spaceui is the source of truth. This writes, under spike/spaceui:
  shared/tokens.mjs              design-tokens.json as an ES module (QML and web)
  shared/nexus-plasma-512.png    the approved core, downscaled with premultiplied alpha
  native/plasma.frag(.qsb)       the shared shader body wrapped for Qt (GLSL 440)
  web/plasma-shader.mjs          the same body wrapped for WebGL2 (GLSL ES 3.00)

Usage: build_shared.py [--no-qsb]   (qsb comes from qt6.qtshadertools)
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DESIGN = ROOT / "docs/design/spaceui"
SPIKE = ROOT / "spike/spaceui"
UNIFORMS = ["u_time", "u_energy", "u_awake", "u_envelope", "u_strands"]
ASSET_SIZE = 512

QT_HEAD = """#version 440
layout(location = 0) in vec2 qt_TexCoord0;
layout(location = 0) out vec4 fragColor;
layout(std140, binding = 0) uniform buf {
    mat4 qt_Matrix;
    float qt_Opacity;
%s
};
layout(binding = 1) uniform sampler2D source;
vec4 sampleCore(vec2 uv) { return texture(source, uv); }
"""
QT_MAIN = "void main() { fragColor = nexusPlasma(qt_TexCoord0) * qt_Opacity; }\n"

WEB_HEAD = """#version 300 es
precision highp float;
in vec2 v_uv;
out vec4 fragColor;
%s
uniform sampler2D source;
vec4 sampleCore(vec2 uv) { return texture(source, uv); }
"""
WEB_MAIN = "void main() { fragColor = nexusPlasma(v_uv); }\n"


def body():
    return (SPIKE / "shared/plasma-core.glsl").read_text()


def qt_shader():
    fields = "\n".join(f"    float {u};" for u in UNIFORMS)
    return QT_HEAD % fields + body() + QT_MAIN


def web_shader():
    fields = "\n".join(f"uniform float {u};" for u in UNIFORMS)
    return WEB_HEAD % fields + body() + WEB_MAIN


def tokens_module():
    tokens = json.loads((DESIGN / "design-tokens.json").read_text())
    layout = json.loads((SPIKE / "shared/layout.json").read_text())
    return ("// Generated by scripts/spike/build_shared.py from docs/design/spaceui/design-tokens.json\n"
            "// and spike/spaceui/shared/layout.json. Do not edit.\n"
            f"export const tokens = {json.dumps(tokens, indent=1)};\n"
            f"export const layout = {json.dumps(layout, indent=1)};\n")


def downscale_asset(dest):
    from PIL import Image
    src = Image.open(DESIGN / "assets/nexus-plasma-original.png").convert("RGBA")
    # "RGBa" is Pillow's premultiplied mode: filtering there keeps hidden RGB
    # under transparent pixels from bleeding into the glow (see the pack README).
    small = src.convert("RGBa").resize((ASSET_SIZE, ASSET_SIZE), Image.LANCZOS).convert("RGBA")
    small.save(dest, optimize=True)


def main(argv):
    out = {
        SPIKE / "shared/tokens.mjs": tokens_module(),
        SPIKE / "native/plasma.frag": qt_shader(),
        SPIKE / "web/plasma-shader.mjs":
            "// Generated by scripts/spike/build_shared.py from shared/plasma-core.glsl. Do not edit.\n"
            f"export const UNIFORMS = {json.dumps(UNIFORMS)};\n"
            f"export const fragmentSource = {json.dumps(web_shader())};\n",
    }
    for path, text in out.items():
        path.write_text(text)
    downscale_asset(SPIKE / "shared/nexus-plasma-512.png")
    if "--no-qsb" not in argv:
        qsb = shutil.which("qsb")
        if not qsb:
            sys.exit("qsb not found: run inside `nix develop .#spaceui-spike`")
        frag = SPIKE / "native/plasma.frag"
        subprocess.run([qsb, "--glsl", "100es,120,150", "--hlsl", "50", "--msl", "12",
                        "-o", str(frag) + ".qsb", str(frag)], check=True)
    print("generated:", ", ".join(str(p.relative_to(ROOT)) for p in out))


if __name__ == "__main__":
    main(sys.argv[1:])
