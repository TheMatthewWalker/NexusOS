#!/usr/bin/env python3
"""Assemble the Nexus shell (Quickshell config) into an output directory.

Copies shell/qml and generates, under <out>/lib:
  tokens.mjs              design tokens (docs/design/spaceui) plus shell/layout.json
  bundles.mjs             the first-run bundles (nix/bundles/*.json), checked
  nova.frag, nova.frag.qsb  the Nova core shader (lib/nova-core.glsl) wrapped for Qt
  nova-noise-atlas.png    the Nova study's 64^3 noise field as padded 2D tiles

Usage: build.py --out DIR [--design DIR] [--no-qsb]
The Nix package (nix/packages/nexus-shell.nix) runs this; for development:
  python3 shell/tools/build.py --out shell/build && quickshell -p shell/build/shell.qml
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

SHELL = Path(__file__).resolve().parents[1]
ROOT = SHELL.parent

QT_HEAD = """#version 440
layout(location = 0) in vec2 qt_TexCoord0;
layout(location = 0) out vec4 fragColor;
layout(std140, binding = 0) uniform buf {
    mat4 qt_Matrix;
    float qt_Opacity;
    mat4 uRot;
    vec3 uPal;
    vec2 uSize;
    vec2 uCenter;
    float uCoreR, uTime, uEnergy, uBeat, uVoice, uListen, uThink, uRipple, uAwake, uSteps;
};
layout(binding = 1) uniform sampler2D uNoise;

// Qt items cannot sample 3D textures, so the 64^3 field is packed as 8x8 tiles
// of 64x64, each with a 1-texel wrapped border so bilinear filtering never
// bleeds between tiles. Two fetches give the same smooth noise as the study.
float n3(vec3 p) {
    vec3 i = floor(p), f = fract(p);
    f = f * f * (3.0 - 2.0 * f);
    vec2 xy = mod(i.xy, 64.0) + f.xy;
    float z0 = mod(i.z, 64.0), z1 = mod(i.z + 1.0, 64.0);
    vec2 a = vec2(mod(z0, 8.0), floor(z0 / 8.0)) * 66.0 + 1.5 + xy;
    vec2 b = vec2(mod(z1, 8.0), floor(z1 / 8.0)) * 66.0 + 1.5 + xy;
    return mix(texture(uNoise, a / 528.0).r, texture(uNoise, b / 528.0).r, f.z);
}
vec3 rot(vec3 v) { return (vec4(v, 0.0) * uRot).xyz; }
"""
QT_MAIN = """
void main() {
    vec2 frag = qt_TexCoord0 * uSize;
    vec2 p = vec2(frag.x - uCenter.x, uCenter.y - frag.y) / uCoreR;
    vec2 e = min(frag, uSize - frag) / (0.18 * uSize);
    fragColor = novaCore(frag, p, clamp(min(e.x, e.y), 0.0, 1.0)) * qt_Opacity;
}
"""


def nova_shader(qml: Path) -> str:
    return QT_HEAD + (qml / "lib/nova-core.glsl").read_text() + QT_MAIN


def noise_volume() -> bytearray:
    """The Nova study's noise field: the same LCG and x-fastest order as its texImage3D."""
    seed, vol = 1234567, bytearray(64 ** 3)
    for i in range(len(vol)):
        seed = (seed * 1664525 + 1013904223) & 0xFFFFFFFF
        vol[i] = seed >> 24
    return vol


def noise_atlas(dest: Path) -> None:
    from PIL import Image
    vol, size = noise_volume(), 8 * 66
    atlas = bytearray(size * size)
    for z in range(64):
        tx, ty = (z % 8) * 66, (z // 8) * 66
        plane = 4096 * z
        for k in range(-1, 65):
            row = (ty + 1 + k) * size + tx
            src = plane + 64 * (k % 64)
            atlas[row:row + 66] = bytes(vol[src + (j % 64)] for j in range(-1, 65))
    Image.frombytes("L", (size, size), bytes(atlas)).save(dest)


def tokens_module(design: Path) -> str:
    tokens = json.loads((design / "design-tokens.json").read_text())
    layout = json.loads((SHELL / "layout.json").read_text())
    return ("// Generated by shell/tools/build.py from docs/design/spaceui/design-tokens.json\n"
            "// and shell/layout.json. Do not edit.\n"
            f"export const tokens = {json.dumps(tokens, indent=1)};\n"
            f"export const layout = {json.dumps(layout, indent=1)};\n")


# First-run bundles (feature 4) are curated data: Flathub apps installed for the
# person, system items (nixpkgs packages or Guardian options) sent as one
# Guardian plan, and personal settings the shell applies. Checked here so a
# typo fails the build instead of reaching anyone's computer.
FLATHUB_ID = re.compile(r"^[A-Za-z][A-Za-z0-9_-]*(\.[A-Za-z0-9_-]+){2,}$")
PACKAGE_ATTR = re.compile(r"^[A-Za-z_][A-Za-z0-9_-]{0,63}(\.[A-Za-z_][A-Za-z0-9_-]{0,63}){0,3}$")
BUNDLE_SETTINGS = {"nightLight": bool, "highContrast": bool, "animations": bool, "blur": bool, "windows": str}


def bundles_module() -> str:
    options = json.loads((ROOT / "schema/guardian-options.json").read_text())["options"]
    bundles = []
    for path in sorted((ROOT / "nix/bundles").glob("*.json")):
        b = json.loads(path.read_text())
        where = path.name
        assert b["id"] == path.stem and b["label"] and b["keywords"], where
        for app in b["apps"]:
            assert FLATHUB_ID.match(app["flathub"]) and app["name"] and app["detail"], (where, app)
        for item in b["system"]:
            if "package" in item:
                assert PACKAGE_ATTR.match(item["package"]), (where, item)
            else:
                assert item["option"] in options and isinstance(item["enabled"], bool), (where, item)
            assert item["name"] and item["detail"], (where, item)
        for setting in b["settings"]:
            assert isinstance(setting["value"], BUNDLE_SETTINGS[setting["key"]]), (where, setting)
        bundles.append(b)
    bundles.sort(key=lambda b: b["order"])
    return ("// Generated by shell/tools/build.py from nix/bundles/*.json. Do not edit.\n"
            f"export const bundles = {json.dumps(bundles, indent=1, ensure_ascii=False)};\n")


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--design", type=Path, default=ROOT / "docs/design/spaceui")
    ap.add_argument("--no-qsb", action="store_true")
    args = ap.parse_args(argv)
    out = args.out.resolve()
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(SHELL / "qml", out)
    lib = out / "lib"
    (lib / "tokens.mjs").write_text(tokens_module(args.design))
    (lib / "bundles.mjs").write_text(bundles_module())
    (lib / "nova.frag").write_text(nova_shader(SHELL / "qml"))
    noise_atlas(lib / "nova-noise-atlas.png")
    if not args.no_qsb:
        qsb = shutil.which("qsb")
        if not qsb:
            sys.exit("qsb not found (qt6.qtshadertools)")
        subprocess.run([qsb, "--glsl", "300es,150", "--hlsl", "50", "--msl", "12",
                        "-o", str(lib / "nova.frag.qsb"), str(lib / "nova.frag")], check=True)
    print(f"nexus shell assembled in {out}")


if __name__ == "__main__":
    main(sys.argv[1:])
